function backtestMaBullish(
  bars: Bar[],
  symbol: string,
  holdingPeriod: number
): Trade[] {
  const trades: Trade[] = [];
  const closes = bars.map((b) => b.c);

  for (let i = 50; i < bars.length - holdingPeriod; i++) {
    const currentPrice = closes[i]!;
    const sma20 = sma(closes.slice(0, i + 1), 20);
    const sma50 = sma(closes.slice(0, i + 1), 50);

    const prevPrice = closes[i - 1]!;
    const prevSma20 = sma(closes.slice(0, i), 20);
    const prevSma50 = sma(closes.slice(0, i), 50);

    const isBullish = currentPrice > sma20 && sma20 > sma50;
    const wasBullish = prevPrice > prevSma20 && prevSma20 > prevSma50;

    if (isBullish && !wasBullish) {
      const entryBar = bars[i]!;
      const exitBar = bars[i + holdingPeriod]!;
      const entryPrice = entryBar.c;
      const exitPrice = exitBar.c;
      const pnlPercent = ((exitPrice - entryPrice) / entryPrice) * 100;

      trades.push({
        symbol,
        signal: "MA_BULLISH_ALIGNMENT",
        entryDate: entryBar.t,
        entryPrice,
        exitDate: exitBar.t,
        exitPrice,
        holdingDays: holdingPeriod,
        pnlPercent,
      });

      i += holdingPeriod;
    }
  }

  return trades;
}

function analyzeResults(trades: Trade[], strategyName: string) {
  if (trades.length === 0) {
    return { strategyName, totalTrades: 0, winRate: 0, avgPnl: 0, totalReturn: 0 };
  }

  const winners = trades.filter((t) => t.pnlPercent > 0);
  const winRate = (winners.length / trades.length) * 100;
  const avgPnl = trades.reduce((a, b) => a + b.pnlPercent, 0) / trades.length;
  const totalReturn = trades.reduce((a, b) => a + b.pnlPercent, 0);

  return { strategyName, totalTrades: trades.length, winRate, avgPnl, totalReturn };
}

